#!/usr/bin/env python3
"""Generate bench/lmsr.fe: the LMSR library (verbatim from ingots/lmsr/src/lib.fe) plus a
thin benchmark contract, because `fe bench` compiles single files. Then run:

    fe bench bench --solc ~/.local/bin/solc
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
lib = (ROOT / "ingots/lmsr/src/lib.fe").read_text()
contract = '''
use std::abi::sol

pub msg BenchMsg {
    #[selector = sol("quoteBuy2(uint256,uint256,uint256,uint256)")]
    QuoteBuy2 { b: u256, q0: u256, q1: u256, x: u256 } -> u256,
    #[selector = sol("quoteBuy4(uint256,uint256,uint256,uint256,uint256,uint256)")]
    QuoteBuy4 { b: u256, q0: u256, q1: u256, q2: u256, q3: u256, x: u256 } -> u256,
    #[selector = sol("price4(uint256,uint256,uint256,uint256,uint256)")]
    Price4 { b: u256, q0: u256, q1: u256, q2: u256, q3: u256 } -> u256,
}

pub contract Bench {
    recv BenchMsg {
        QuoteBuy2 { b, q0, q1, x } -> u256 {
            Lmsr<2>::new(b: Wad::from_raw(b)).buy_cost([Wad::from_raw(q0), Wad::from_raw(q1)], i: 0, shares: Wad::from_raw(x)).raw()
        }
        QuoteBuy4 { b, q0, q1, q2, q3, x } -> u256 {
            Lmsr<4>::new(b: Wad::from_raw(b))
                .buy_cost([Wad::from_raw(q0), Wad::from_raw(q1), Wad::from_raw(q2), Wad::from_raw(q3)], i: 0, shares: Wad::from_raw(x))
                .raw()
        }
        Price4 { b, q0, q1, q2, q3 } -> u256 {
            Lmsr<4>::new(b: Wad::from_raw(b)).price([Wad::from_raw(q0), Wad::from_raw(q1), Wad::from_raw(q2), Wad::from_raw(q3)], i: 0).raw()
        }
    }
}
'''
(ROOT / "bench/lmsr.fe").write_text("// GENERATED by tools/make_bench.py from ingots/lmsr/src/lib.fe. Do not edit.\n" + lib + contract)
print("wrote bench/lmsr.fe")
