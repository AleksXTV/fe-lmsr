#!/usr/bin/env python3
"""Differential test: the Fe LMSR (compiled natively) against a 60-digit reference.

    python3 tools/difftest.py [--cases 20000] [--seed 1] [--bin ingots/lmsr-cli/out/lmsr_cli]

For every random market it checks, in raw 18-decimal units (wei):
  * bracket:  cost_lower <= C_true <= cost_upper           (what solvency relies on)
  * accuracy: |cost - C_true| and |price_i - p_true_i|
It also writes ingots/lmsr/src/vectors.fe, a sample of the cases as `fe test`
assertions (`--vectors 300`), so the bracket property is checked in CI without Python.
Needs only the Python standard library.
"""
from __future__ import annotations

import argparse
import random
import subprocess
import sys
from decimal import Decimal, getcontext
from pathlib import Path

getcontext().prec = 60
E18 = Decimal(10) ** 18
ROOT = Path(__file__).resolve().parent.parent
NS = [2, 3, 4, 8, 16]


def reference(b: int, q: list[int]) -> tuple[Decimal, list[Decimal]]:
    bd = Decimal(b) / E18
    xs = [Decimal(x) / E18 / bd for x in q]
    m = max(xs)
    ws = [(x - m).exp() for x in xs]
    s = sum(ws)
    cost = bd * (m + s.ln())
    return cost * E18, [w / s * E18 for w in ws]


def random_market(rnd: random.Random) -> tuple[int, int, list[int]]:
    n = rnd.choice(NS)
    regime = rnd.random()
    b = int(10 ** rnd.uniform(-3, 12) * 10**18)  # 0.001 .. 10^12
    if regime < 0.15:
        q = [0] * n
    elif regime < 0.5:  # moderate positions, comparable to b
        q = [int(rnd.uniform(0, 5) * b) for _ in range(n)]
    elif regime < 0.8:  # one dominant outcome
        q = [int(rnd.uniform(0, 2) * b) for _ in range(n)]
        q[rnd.randrange(n)] += int(rnd.uniform(5, 60) * b)
    else:  # anything up to the supported share limit
        q = [int(10 ** rnd.uniform(0, 33)) for _ in range(n)]
    cap = 10**15 * 10**18
    return n, b, [min(x, cap) for x in q]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--cases", type=int, default=20000)
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--bin", default=str(ROOT / "ingots/lmsr-cli/out/lmsr_cli"))
    ap.add_argument("--vectors", type=int, default=300, help="0 = do not rewrite vectors.fe")
    a = ap.parse_args()
    rnd = random.Random(a.seed)
    cases = [random_market(rnd) for _ in range(a.cases)]
    inp = "".join(f"{n} {b} {' '.join(map(str, q))}\n" for n, b, q in cases)
    out = subprocess.run([a.bin], input=inp, capture_output=True, text=True, check=True).stdout.splitlines()
    assert len(out) == len(cases), (len(out), len(cases))
    bracket_fail = 0
    worst_cost_rel_bound = Decimal(0)  # |cost - true| / error_bound
    worst_cost_abs = Decimal(0)
    worst_price = Decimal(0)
    price_sum_dev = Decimal(0)
    vec = []
    for (n, b, q), line in zip(cases, out):
        v = list(map(int, line.split()))
        cost, lo, hi, prices = v[0], v[1], v[2], v[3:]
        true_c, true_p = reference(b, q)
        if not (lo <= true_c <= hi):
            bracket_fail += 1
            print("BRACKET FAIL", n, b, q, lo, true_c, hi, file=sys.stderr)
        bound = Decimal(hi - cost)
        err = abs(Decimal(cost) - true_c)
        worst_cost_abs = max(worst_cost_abs, err)
        if bound > 0:
            worst_cost_rel_bound = max(worst_cost_rel_bound, err / bound)
        worst_price = max(worst_price, max(abs(Decimal(p) - t) for p, t in zip(prices, true_p)))
        price_sum_dev = max(price_sum_dev, abs(sum(prices) - E18))
        if len(vec) < a.vectors and n in (2, 4, 8):
            vec.append((n, b, q, int(true_c), int(true_c) + 1))
    print(f"cases: {len(cases)}  (N in {NS}, b from 0.001 to 1e12, shares up to 1e15)")
    print(f"bracket cost_lower <= C_true <= cost_upper: {len(cases) - bracket_fail}/{len(cases)} hold")
    print(f"worst |cost - C_true|: {worst_cost_abs:.0f} wei; worst error / error_bound: {worst_cost_rel_bound:.4f}")
    print(f"worst |price - p_true|: {worst_price:.1f} wei; worst |sum(prices) - 1|: {price_sum_dev:.0f} wei")
    if a.vectors > 0:
        write_vectors(vec)
    return 1 if bracket_fail else 0


def write_vectors(vec) -> None:
    lines = ["// Generated by tools/difftest.py from 60-digit Decimal references. Do not edit.",
             "// Each case asserts cost_lower(q) <= floor(C_true) and ceil(C_true) <= cost_upper(q).",
             "use ingot::Lmsr", "use core::fixed::Wad", ""]
    by_n: dict[int, list] = {}
    for c in vec:
        by_n.setdefault(c[0], []).append(c)
    for n, cs in sorted(by_n.items()):
        lines.append(f"fn check{n}(b: u256, q: [u256; {n}], floor: u256, ceil: u256) {{")
        lines.append(f"    var w: [Wad; {n}] = [Wad::zero(); {n}]")
        lines.append(f"    var i: usize = 0")
        lines.append(f"    while i < {n} {{")
        lines.append(f"        w[i] = Wad::from_raw(q[i])")
        lines.append(f"        i += 1")
        lines.append(f"    }}")
        lines.append(f"    let m = Lmsr<{n}>::new(b: Wad::from_raw(b))")
        lines.append(f"    assert!(m.cost_lower(w).raw() <= floor)")
        lines.append(f"    assert!(m.cost_upper(w).raw() >= ceil)")
        lines.append("}")
        lines.append("")
        for k in range(0, len(cs), 25):
            lines.append("#[test]")
            lines.append(f"fn reference_vectors_n{n}_{k // 25}() {{")
            for _, b, q, fl, ce in cs[k:k + 25]:
                lines.append(f"    check{n}(b: {b}, q: [{', '.join(map(str, q))}], floor: {fl}, ceil: {ce})")
            lines.append("}")
            lines.append("")
    (ROOT / "ingots/lmsr/src/vectors.fe").write_text("\n".join(lines))


if __name__ == "__main__":
    sys.exit(main())
